class DirectorAgent:
    """
    Director agent that orchestrates the research workflow with tool agents using a persistent
    multi-turn conversation (messages list) to iteratively refine research and
    generate queries for tool agents.

    This agent focuses on directing the research by generating actionable queries
    for tool agents. For hypothesis generation, use HypothesisGenAgent.
    """

    def __init__(
        self,
        config: HypothesisGenerationConfig,
        tool_agent_prompt: str = None,
        logger=None,
    ):
        """
        Initialize the multi-turn director agent.

        Args:
            config (HypothesisGenerationConfig): Full configuration object
            tool_agent_prompt (str, optional): Description of available tool agents
            logger (Logger, optional): Shared logger instance. If None, creates a new one.
        """
        self.config = config

        self.llm_config = getattr(self.config, "llm_config", None)
        self.log_dir = getattr(self.config, "log_dir", None)
        self.mcp_servers = getattr(self.config, "mcp_servers", None)
        self.multiturn_prompt = getattr(self.config, "multiturn_prompt", None)

        self.allow_director_to_stop = getattr(self.config, "allow_director_to_stop", True)

        # Use DIRECTOR_AGENT_SYSTEM_PROMPT as default, allow override via config
        config_system_prompt = getattr(self.config, "system_prompt", None)
        if config_system_prompt:
            self.system_prompt = config_system_prompt
        else:
            self.system_prompt = DIRECTOR_AGENT_SYSTEM_PROMPT

        if tool_agent_prompt:
            self.system_prompt += f"\n\n# Helper Agents\n\n{tool_agent_prompt}"

        # Add resource information if running on SLURM
        resource_info = get_slurm_resource_info()
        if resource_info:
            self.system_prompt += f"\n\n{resource_info}"

        if self.allow_director_to_stop:
            self.system_prompt += STOP_PROMPT

        self.system_prompt += "\n\n" + REACT_PROMPT

        # Use passed logger or create a new one if not provided
        self.logger = logger if logger is not None else Logger("director_agent", log_dir=self.log_dir)

        # Log the system prompt for debugging and transparency
        try:
            self.logger.log_action("system_prompt_initialized", f"System prompt length: {len(self.system_prompt)} characters")
            self.logger.log_prompt("system", self.system_prompt, "director_agent_system_prompt")
        except Exception:
            print(f"📝 Director agent system prompt initialized: {len(self.system_prompt)} characters")

        # Initialize client based on API provider
        if not self.llm_config.api_key:
            raise ValueError("ANTHROPIC_API_KEY environment variable not set")
        self.client = anthropic.Anthropic(api_key=self.llm_config.api_key)
        self.logger.log_action("llm_client_init", f"Using Anthropic API with model: {self.llm_config.model_name}")

        # Persistent conversation messages
        # The system prompt is passed separately from the messages.
        self.messages: List[Dict[str, Any]] = []

        # Compaction settings (Anthropic only, requires claude-opus-4-6)
        self.compaction_enabled = (
            getattr(self.config, 'enable_compaction', False)
            and self.llm_config.api_provider == 'anthropic'
            and 'claude-opus-4-6' in self.llm_config.model_name
        )
        self.compaction_trigger_tokens = getattr(self.config, 'compaction_trigger_tokens', 150000)
        self.compaction_instructions = getattr(self.config, 'compaction_instructions', COMPACTION_PROMPT)

        # Default research-specific compaction instructions
        if self.compaction_enabled and self.compaction_instructions is None:
            self.compaction_instructions = COMPACTION_PROMPT

        if self.compaction_enabled:
            self.logger.log_action("compaction_enabled",
                f"Compaction enabled with trigger at {self.compaction_trigger_tokens} tokens")

        self.background_report_read = False
        self.target_hypothesis_read = False
        self.exploratory_mode_prompted = False

    def estimate_context_tokens(self) -> int:
        """Estimate input tokens for the current conversation state."""
        try:
            count_info = count_anthropic_tokens(
                client=self.client,
                model_name=self.llm_config.model_name,
                messages=self.messages,
                system=self.system_prompt,
            )
            tokens = int(count_info.get("input_tokens", 0))
            self.logger.log_action("token_estimate", f"Estimated input tokens (multi-turn): {tokens}")
            return tokens
        except Exception as e:
            self.logger.log_error(f"Token estimation failed (multi-turn): {str(e)}")
            return 0

    def _extract_text_from_anthropic_response(self, response) -> str:
        """Safely extract concatenated text blocks from an Anthropic response, even when tools are used."""
        text_parts = []
        try:
            for block in getattr(response, "content", []):
                if getattr(block, "type", None) == "text" and hasattr(block, "text"):
                    text_parts.append(block.text)
            return "\n".join(part for part in text_parts if part)
        except Exception as e:
            self.logger.log_error(
                f"Failed to extract text from response: {type(e).__name__}: {e}\n"
                f"response: {describe_response(response)}"
            )
            return ""

    def _call_api_with_retry(self, api_params: dict, max_retries: int = 5, wait_time: int = 60) -> str:
        """
        Call the LLM API with retry logic for handling transient errors.

        Args:
            api_params: Parameters to pass to the API
            max_retries: Maximum number of retry attempts (default: 5)
            wait_time: Time to wait between retries in seconds (default: 60)

        Returns:
            str: The response text from the API

        Raises:
            Exception: If all retry attempts fail
        """
        # Track raw response content for compaction block preservation
        self._last_response_content = None
        # Set when Anthropic declines this call, so callers can tell a refusal
        # apart from a malformed completion (they look identical downstream).
        self.last_refusal = None

        # Inject compaction parameters for Anthropic when enabled
        use_beta = bool(self.mcp_servers)
        if self.compaction_enabled and self.llm_config.api_provider == 'anthropic':
            compaction_edit = {
                "type": "compact_20260112",
                "trigger": {"type": "input_tokens", "value": self.compaction_trigger_tokens},
            }
            if self.compaction_instructions:
                compaction_edit["instructions"] = self.compaction_instructions
            api_params["context_management"] = {"edits": [compaction_edit]}

            # Merge compaction beta with any existing betas (e.g. MCP)
            existing_betas = api_params.get("betas", [])
            if "compact-2026-01-12" not in existing_betas:
                api_params["betas"] = existing_betas + ["compact-2026-01-12"]
            use_beta = True

        last_error = None

        for attempt in range(max_retries + 1):  # +1 for initial attempt
            try:
                # Extract beta-only params that the SDK doesn't have typed kwargs for
                call_params = {k: v for k, v in api_params.items() if k != "context_management"}
                extra_body = {}
                if "context_management" in api_params:
                    extra_body["context_management"] = api_params["context_management"]
                if extra_body:
                    call_params["extra_body"] = extra_body

                if self.compaction_enabled:
                    self.logger.log_action("compaction_request",
                        f"Compaction active: use_beta={use_beta}, "
                        f"trigger={self.compaction_trigger_tokens}, "
                        f"has_context_mgmt={'context_management' in api_params}, "
                        f"betas={call_params.get('betas', [])}")

                response = self.client.beta.messages.create(**call_params) if use_beta else self.client.messages.create(**call_params)

                # Store raw content blocks when compaction is enabled
                # Convert SDK objects to dicts for JSON serialization (checkpointing)
                if self.compaction_enabled:
                    self._last_response_content = [
                        block.model_dump() if hasattr(block, 'model_dump') else block
                        for block in response.content
                    ]
                    # Check if compaction was triggered
                    for block in self._last_response_content:
                        block_type = block.get("type") if isinstance(block, dict) else getattr(block, "type", None)
                        if block_type == "compaction":
                            summary = block.get("content", "") if isinstance(block, dict) else getattr(block, "content", "")
                            self.logger.log_action("compaction_triggered",
                                f"Context compacted (summary: {len(summary)} chars)")
                            break

                text = self._extract_text_from_anthropic_response(response)
                log_api_exchange(self.logger, "DirectorAgent", call_params, response, text)
                self.last_refusal = refusal_notice(response)
                return text

            except (anthropic.InternalServerError, anthropic.APIError) as e:
                last_error = e
                error_msg = str(e)

                # Detect context overflow and auto-enable compaction (claude-opus-4-6 only)
                if ("prompt is too long" in error_msg
                        and self.llm_config.api_provider == 'anthropic'
                        and 'claude-opus-4-6' in self.llm_config.model_name
                        and not self.compaction_enabled):
                    self.logger.log_action("context_overflow_detected",
                        f"Prompt exceeded context window. Enabling compaction and retrying...")
                    self.compaction_enabled = True
                    # Set trigger to minimum so compaction fires immediately on retry
                    self.compaction_trigger_tokens = 50000
                    if self.compaction_instructions is None:
                        self.compaction_instructions = COMPACTION_PROMPT
                    # Inject compaction params for the retry
                    compaction_edit = {
                        "type": "compact_20260112",
                        "trigger": {"type": "input_tokens", "value": self.compaction_trigger_tokens},
                        "instructions": self.compaction_instructions,
                    }
                    api_params["context_management"] = {"edits": [compaction_edit]}
                    existing_betas = api_params.get("betas", [])
                    if "compact-2026-01-12" not in existing_betas:
                        api_params["betas"] = existing_betas + ["compact-2026-01-12"]
                    use_beta = True
                    continue  # Retry with compaction enabled

                # Check if this is a retryable error
                if "Overloaded" in error_msg or "500" in error_msg or "503" in error_msg or "429" in error_msg:
                    if attempt < max_retries:
                        self.logger.log_action(
                            "api_retry",
                            f"API error (attempt {attempt + 1}/{max_retries + 1}): {error_msg}. "
                            f"Waiting {wait_time} seconds before retry..."
                        )
                        time.sleep(wait_time)
                        continue
                    else:
                        self.logger.log_error(f"Max retries ({max_retries}) reached.")
                        log_api_exception(
                            self.logger,
                            e,
                            source="DirectorAgent",
                            api_params=api_params,
                            retryable=False,
                        )
                        raise Exception(f"API call failed after {max_retries} retries: {error_msg}")
                else:
                    # Non-retryable error, raise immediately
                    log_api_exception(
                        self.logger,
                        e,
                        source="DirectorAgent",
                        api_params=api_params,
                        retryable=False,
                    )
                    raise

            except Exception as e:
                # For unexpected errors, raise immediately without retry
                last_error = e
                log_api_exception(
                    self.logger,
                    e,
                    source="DirectorAgent",
                    api_params=api_params,
                    retryable=False,
                )
                raise

        # If we somehow exit the loop without returning or raising
        if last_error:
            raise Exception(f"API call failed: {str(last_error)}")
        raise Exception("API call failed for unknown reason")

    def extract_query(self, text: str) -> Optional[str]:
        """Extract the content within <query>...</query> from a text block."""
        query_pattern = r"<query>(.*?)</query>"
        match = re.search(query_pattern, text, re.DOTALL)
        if match:
            return match.group(1).strip()
        return None

    def add_user_message(self, content: str) -> None:
        """Append a user message to the conversation and log it."""
        self.messages.append({"role": "user", "content": content})
        self.logger.log_prompt("user", content, "Director Agent Query Generation")

    def add_assistant_message(self, content) -> None:
        """Append an assistant message to the conversation and log it.

        Args:
            content: Either a string or a list of content blocks (when compaction is active).
        """
        self.messages.append({"role": "assistant", "content": content})
        # Log the text portion for readability
        if isinstance(content, str):
            self.logger.log_response(content, "director_agent_query_generation")
        else:
            # Content is a list of blocks; extract text for logging
            text_parts = []
            for block in content:
                block_type = getattr(block, "type", None) or (block.get("type") if isinstance(block, dict) else None)
                if block_type == "text":
                    text_parts.append(getattr(block, "text", None) or block.get("text", ""))
            self.logger.log_response("\n".join(text_parts), "director_agent_query_generation")

    def generate_query(
        self,
        dataset_description: str = None,
        report: str = "",
        query_count: int = 1,
        total_queries: int = 10,
        feedback: str = "",
        after_hypothesis_step: bool = False,
        background_report: str = None,
        target_hypothesis: str = None,
        human_selection_mode: bool = False,
        exploratory_mode: bool = False,
    ) -> Optional[str]:
        """
        Generate a query for tool agents using the multi-turn conversation context.

        Args:
            dataset_description (str): Description of the dataset
            report (str): Report from previous queries in the current round
            query_count (int): Current query number
            total_queries (int): Total number of queries allowed
            feedback (str): Feedback from reviewer
            after_hypothesis_step (bool): Whether this is after a hypothesis generation step
            background_report (str): Accumulated knowledge from previous rounds
            target_hypothesis (str): Hypothesis to test (only fed in on first query, then in context)
            human_selection_mode (bool): If True, director explores for human hypothesis selection
            exploratory_mode (bool): If True, director explores data without a specific hypothesis

        Returns:
            Optional[str]: Extracted query from the response, or None if no query found
        """
        # Build the prompt turn for this step
        turn_prompt = ""

        # Add current round's report or dataset/task description
        if report:
            turn_prompt += REPORT_MULTITURN_PROMPT.format(
                report=report,
            )
        elif (not after_hypothesis_step):
            turn_prompt += DATASET_DESCRIPTION_PROMPT.format(
                dataset_description=dataset_description
            )
        # Add background report if available (accumulated knowledge from previous rounds)
        if background_report and (not self.background_report_read):
            turn_prompt += BACKGROUND_REPORT_PROMPT.format(
                background_report=background_report
            ) + "\n\n"
            self.background_report_read = True

        # Inject mode-specific prompt (only on first query, then it's in context)
        # Two modes: Hypothesis Orchestration (with hypothesis) or Exploratory (no hypothesis)
        if target_hypothesis and (not self.target_hypothesis_read): # Feed in if we haven't before
            # HYPOTHESIS ORCHESTRATION MODE: Test the provided hypothesis
            if human_selection_mode:
                target_hypothesis_prompt = TARGET_HYPOTHESIS_HUMAN_SELECTION_PROMPT.format(
                    target_hypothesis=target_hypothesis
                )
            else:
                target_hypothesis_prompt = AUTO_TARGET_HYPOTHESIS_PROMPT.format(
                    target_hypothesis=target_hypothesis
                )

            turn_prompt += HYPOTHESIS_ORCHESTRATION_PROMPT.format(
                target_hypothesis_prompt=target_hypothesis_prompt
            ) + "\n\n"
            self.target_hypothesis_read = True
            self.logger.log_action("hypothesis_orchestration_mode", 
                f"Hypothesis orchestration prompt injected ({len(target_hypothesis)} chars hypothesis)")
        elif exploratory_mode and (not target_hypothesis) and (not self.exploratory_mode_prompted):
            # EXPLORATORY MODE: Explore data without a specific hypothesis
            turn_prompt += EXPLORATORY_MODE_PROMPT + "\n\n"
            self.exploratory_mode_prompted = True
            self.logger.log_action("exploratory_mode", 
                "Exploratory mode prompt injected")

        turn_prompt += f"\n\nYou have {total_queries - query_count + 1} / {total_queries} queries left."
        if target_hypothesis and (not exploratory_mode):
            turn_prompt += "\n\nYou are in hypothesis orchestration mode. You should now continue to test the hypothesis, using this information as context for your next query. Remember to stick to the plan for testing the hypothesis; do not deviate into unrelated explorations."
        else:
            if self.multiturn_prompt is not None:
                turn_prompt += "\n\n" + self.multiturn_prompt
            else:
                turn_prompt += "\n\nPlease submit your next query to one of the helper agents provided to you."

        if feedback:
            turn_prompt += f"\n\nYour work from the previous query was also fed into a reviewer agent, and it provided the following feedback: {feedback}"
            turn_prompt += "\n\nUse this feedback to improve your research."

        if report:
            turn_prompt += """
First produce an interpretation of the report that was returned to you via your previous query. Your output should look like this:
**Interpretation**: [Your interpretation of the report from the previous query]
**Thought**: [Your reasoning and plan for this step]
<[tag]>
[Your query to the appropriate helper agent]
</[tag]>
"""

        if self.allow_director_to_stop:
            turn_prompt += "\n\n" + STOP_PROMPT_SHORT

        # Add as a new user turn
        self.add_user_message(turn_prompt)

        try:
            # Prepare API call parameters
            api_params = {
                "model": self.llm_config.model_name,
                "max_tokens": self.config.max_tokens,
                "system": self.system_prompt,
                "messages": self.messages,
            }

            # Add MCP servers and betas if configured (Anthropic only)
            if self.llm_config.api_provider == 'anthropic' and self.mcp_servers:
                api_params["mcp_servers"] = self.mcp_servers
                api_params["betas"] = ["mcp-client-2025-04-04"]

            # Call API with retry logic
            result_text = self._call_api_with_retry(api_params)

            # Store raw content blocks (with compaction block) when compaction is active,
            # otherwise store text string. The compaction block must be passed back to
            # the API on subsequent turns for the server to drop pre-compaction messages.
            if self.compaction_enabled and self._last_response_content is not None:
                self.add_assistant_message(self._last_response_content)
            else:
                self.add_assistant_message(result_text)

            return result_text

        except Exception as e:
            error_msg = f"Error generating query (multi-turn): {str(e)}"
            self.logger.log_error(error_msg)
            raise Exception(error_msg)

    def generate_final_report(self, report: str) -> Optional[str]:
        """
        Generate a final structured report summarizing all findings.

        This method takes the cumulative report from all queries and asks the LLM
        to produce a polished, structured final report following scientific writing
        standards with sections for Background, Data Characteristics, Experiments
        and Analyses, and Discussion.

        Args:
            report (str): Cumulative report from all queries executed so far

        Returns:
            Optional[str]: Generated final report, or None if generation fails
        """
        # Build the prompt with the cumulative report and the report structure instructions
        final_report_prompt = CONTINUATION_REPORT_PROMPT + f"\n\nHere is the cumulative report from all of your queries and analyses:\n\n{report}"

        # Add as a new user turn
        self.add_user_message(final_report_prompt)

        try:
            # Prepare API call parameters
            api_params = {
                "model": self.llm_config.model_name,
                "max_tokens": self.config.max_tokens,
                "system": self.system_prompt,
                "messages": self.messages,
            }

            # Add MCP servers and betas if configured (Anthropic only)
            if self.llm_config.api_provider == 'anthropic' and self.mcp_servers:
                api_params["mcp_servers"] = self.mcp_servers
                api_params["betas"] = ["mcp-client-2025-04-04"]

            # Call API with retry logic
            result_text = self._call_api_with_retry(api_params)

            # Store raw content blocks when compaction is active
            if self.compaction_enabled and self._last_response_content is not None:
                self.add_assistant_message(self._last_response_content)
            else:
                self.add_assistant_message(result_text)

            self.logger.log_action("final_report_generated",
                f"Generated final report ({len(result_text)} characters)")

            return result_text

        except Exception as e:
            error_msg = f"Error generating final report: {str(e)}"
            self.logger.log_error(error_msg)
            raise Exception(error_msg)


    def reset_conversation(self) -> None:
        """Reset the conversation to the initial state (preserving the system prompt)."""
        self.messages = []
        self.background_report_read = False
        self.target_hypothesis_read = False
        self.exploratory_mode_prompted = False
        self.logger.log_action("conversation_reset", "Conversation reset for director agent (multi-turn)")

    def save_state(self) -> dict:
        """
        Save complete conversation state for checkpointing.

        Returns:
            dict: Complete agent state including full conversation history
        """
        return {
            'agent_type': type(self).__name__,
            'messages': self.messages.copy(),  # Full conversation history
            'system_prompt': self.system_prompt,
            'conversation_length': len(self.messages),
            'background_report_read': self.background_report_read,
            'target_hypothesis_read': self.target_hypothesis_read,
            'exploratory_mode_prompted': self.exploratory_mode_prompted,
            'estimated_tokens': self.estimate_context_tokens(),
            'llm_config': {
                'model_name': self.llm_config.model_name,
                'api_provider': self.llm_config.api_provider,
                'temperature': getattr(self.llm_config, 'temperature', None),
                'frequency_penalty': getattr(self.llm_config, 'frequency_penalty', None),
                'api_key_hash': hash(self.llm_config.api_key) if self.llm_config.api_key else None
            },
            'config_data': {
                'log_dir': self.config.log_dir,
                'max_tokens': self.config.max_tokens,
                'system_prompt': self.config.system_prompt,
                'mcp_servers': self.config.mcp_servers if hasattr(self.config, 'mcp_servers') else []
            },
            'tool_agent_prompt': getattr(self, 'tool_agent_prompt', ''),
            'mcp_servers': self.mcp_servers if hasattr(self, 'mcp_servers') else [],
            'compaction_enabled': self.compaction_enabled,
        }

    def restore_state(self, state: dict) -> bool:
        """
        Restore complete conversation state from checkpoint.

        Args:
            state: State dictionary from checkpoint

        Returns:
            bool: True if restoration was successful
        """
        try:
            # Restore conversation messages
            self.messages = state.get('messages', []).copy()


            # Validate message structure
            for i, msg in enumerate(self.messages):
                if not isinstance(msg, dict) or 'role' not in msg or 'content' not in msg:
                    self.logger.log_error(f"Invalid message structure at index {i}")
                    return False

            # Restore other state if needed (most is already set during initialization)
            self.background_report_read = state.get('background_report_read', False)
            self.target_hypothesis_read = state.get('target_hypothesis_read', False)
            self.exploratory_mode_prompted = state.get('exploratory_mode_prompted', False)
            restored_tokens = state.get('estimated_tokens', 0)
            current_tokens = self.estimate_context_tokens()

            # Log restoration details
            self.logger.log_action("state_restored",
                f"Restored {len(self.messages)} messages, "
                f"tokens: {restored_tokens} -> {current_tokens}")

            # Verify conversation makes sense
            conversation_length = state.get('conversation_length', 0)
            if len(self.messages) != conversation_length:
                self.logger.log_action("conversation_length_mismatch",
                    f"Expected {conversation_length}, got {len(self.messages)}")

            return True

        except Exception as e:
            self.logger.log_error(f"Failed to restore director agent state: {str(e)}")
            return False

